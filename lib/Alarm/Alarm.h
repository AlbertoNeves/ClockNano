#pragma once

#include <Arduino.h>
#include <Buttons.h>
#include <Canvas.h>

namespace Alarm
{

//==========================================================
// Tipo de repetição
//==========================================================

enum class Repeat : uint8_t
{
    Once = 0,
    Daily,
    WeekDays
};

//==========================================================
// Estado da edição
//==========================================================

enum class State : uint8_t
{
    Inactive = 0,
    EditingHour,
    EditingMinute,
    EditingRepeat,
    EditingWeekDays
};

//==========================================================
// Resultado da edição
//==========================================================

enum class Result : uint8_t
{
    None = 0,
    Changed,
    FieldConfirmed,
    Confirmed
};

//==========================================================
// Inicialização
//==========================================================

void begin();

//==========================================================
// Inicia edição do alarme
//==========================================================

void start();

//==========================================================
// Atualiza máquina de estados
//==========================================================

void update(
    const ButtonEvent &event);

//==========================================================
// Renderiza tela
//==========================================================

void draw(
    Canvas &canvas);

//==========================================================
// Estado atual
//==========================================================

State state();

//==========================================================
// Resultado pendente
//==========================================================

bool readResult(
    Result &result);

//==========================================================
// Valores do alarme
//==========================================================

uint8_t hour();

uint8_t minute();

Repeat repeat();

uint8_t weekDays();

//==========================================================
// Cancela edição
//==========================================================

void cancel();

} // namespace Alarm